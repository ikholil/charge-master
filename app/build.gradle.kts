    kotlinOptions { jvmTarget = "17" }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    sourceSets {
        // Exported Room schemas are needed by MigrationTestHelper (Robolectric reads debug assets).
        // Debug-only: release builds never contain them.
        getByName("debug").assets.srcDir("$projectDir/schemas")
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            isReturnDefaultValues = true
            all { test ->
                // Optional: -ProbolectricRepoUrl=<maven mirror> when Maven Central is unreachable/rate-limited.
                (project.findProperty("robolectricRepoUrl") as String?)?.let {
                    test.systemProperty("robolectric.dependency.repo.url", it)
                }
            }
        }
    }

    packaging {
        resources { excludes += "/META-INF/{AL2.0,LGPL2.1}" }
    }
}

